DROP TABLE IF EXISTS app_cm_tweeks;
CREATE TABLE app_cm_tweeks (
	w_id MEDIUMINT(5) UNSIGNED NOT NULL,
	w_start DATE NOT NULL DEFAULT '0000-00-00',
	w_end DATE NOT NULL DEFAULT '0000-00-00',
	PRIMARY KEY (w_id)
) ENGINE=MYISAM DEFAULT CHARSET=utf8 COLLATE=utf8_unicode_ci;

DROP TABLE IF EXISTS app_cm_tinfo;
CREATE TABLE app_cm_tinfo (
  	t_sn VARCHAR(9) COLLATE utf8_unicode_ci NOT NULL UNIQUE,
  	t_week TINYINT(2) NOT NULL DEFAULT 0,
  	t_notes VARCHAR(255) COLLATE utf8_unicode_ci NOT NULL,
  	PRIMARY KEY (t_sn)
) ENGINE=MYISAM DEFAULT CHARSET=utf8 COLLATE=utf8_unicode_ci AUTO_INCREMENT=1;

DROP TABLE IF EXISTS app_cm_tdata;
CREATE TABLE app_cm_tdata (
	c_id MEDIUMINT(5) UNSIGNED NOT NULL AUTO_INCREMENT,
	t_sn VARCHAR(9) COLLATE utf8_unicode_ci NOT NULL,
	t_cell TINYINT(2) NOT NULL,
	t_value TINYINT(2) NOT NULL,
	t_diag TINYINT(1) NOT NULL DEFAULT 0,
	t_date DATE NOT NULL DEFAULT '0000-00-00',
	PRIMARY KEY (c_id)
) ENGINE=MYISAM DEFAULT CHARSET=utf8 COLLATE=utf8_unicode_ci AUTO_INCREMENT=1;

DROP TABLE IF EXISTS app_cm_tnum;
CREATE TABLE app_cm_tnum (
	n_id MEDIUMINT(5) UNSIGNED NOT NULL AUTO_INCREMENT,
	n_date DATE NOT NULL DEFAULT '0000-00-00',
	n_value TINYINT(2) NOT NULL,
	n_lucky TINYINT(1) NOT NULL DEFAULT 0,
	PRIMARY KEY (n_id)
) ENGINE=MYISAM DEFAULT CHARSET=utf8 COLLATE=utf8_unicode_ci AUTO_INCREMENT=1;